#!/usr/bin/env python3
"""Reproduce the dependency-free Unicode 15.0 XID table (Python 3.12)."""
import pathlib
import unicodedata
assert unicodedata.unidata_version == '15.0.0', 'Use Python with Unicode 15.0.0'
root = pathlib.Path(__file__).resolve().parents[1]
rows = []
start = previous = flags = None
for code in range(128, 0x110000):
    char = chr(code)
    current = int(char.isidentifier()) | (int(('a' + char).isidentifier()) << 1)
    if current != flags:
        if flags:
            rows.append((start, code - 1, flags))
        start, flags = code, current
if flags:
    rows.append((start, 0x10ffff, flags))
prefix = '''/* SPDX-License-Identifier: GPL-2.0-or-later */
/* Generated by tools/build_identifier_table.py; Unicode 15.0 XID properties.
 * Start=1, continue=2. No normalization or language keyword semantics. */
#ifndef INSIGHT_IDENTIFIER_H
#define INSIGHT_IDENTIFIER_H
#include <stddef.h>
#include <stdint.h>
static inline unsigned insight_identifier_flags(uint32_t code) {
 static const struct { uint32_t first,last;unsigned flags; } ranges[]={
'''
suffix = ''' };
 if(code<128) return (code=='_' || (code>='a' && code<='z') || (code>='A' && code<='Z')) ? 3 : (code>='0' && code<='9') ? 2 : 0;
 size_t first=0,last=sizeof ranges/sizeof ranges[0];
 while(first<last) { size_t middle=first+(last-first)/2;if(code<ranges[middle].first) last=middle;else if(code>ranges[middle].last) first=middle+1;else return ranges[middle].flags; }
 return 0;
}
/* Decode one scalar, returning byte width, or zero for malformed/truncated UTF-8. */
static inline size_t insight_identifier_decode(const char *s,size_t length,size_t at,uint32_t *code) {
 if(at>=length) return 0;
 const unsigned char *p=(const unsigned char *)s;unsigned a=p[at],need;uint32_t value;
 if(a<128) { *code=a;return a ? 1 : 0; }
 if(a>=0xc2 && a<=0xdf) { need=1;value=a&31; }
 else if(a>=0xe0 && a<=0xef) { need=2;value=a&15; }
 else if(a>=0xf0 && a<=0xf4) { need=3;value=a&7; }else return 0;
 if(length-at-1<need) return 0;
 for(unsigned n=1;n<=need;n++) { unsigned b=p[at+n];if((b&0xc0)!=0x80) return 0;value=(value<<6)|(b&63); }
 if((need==2 && value<0x800) || (need==3 && value<0x10000) || value>0x10ffff || (value>=0xd800 && value<=0xdfff)) return 0;
 *code=value;return need+1;
}
static inline size_t insight_identifier_previous(const char *s,size_t at) {
 if(!at) return 0;
 at--;while(at && ((unsigned char)s[at]&0xc0)==0x80) at--;return at;
}
#endif
'''
(root / 'core/identifier.h').write_text(prefix + ''.join('  {0x%x,0x%x,%u},\n' % row for row in rows) + suffix)
print('Unicode 15.0 identifier table:', len(rows), 'ranges')
